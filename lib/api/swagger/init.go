package swagger

import (
	"html/template"
	"io/fs"
	"mime"
	"path"
	"strings"

	_ "github.com/ether/etherpad-go/docs"
	"github.com/gofiber/fiber/v3"
	swaggerFiles "github.com/swaggo/files/v2"
	"github.com/swaggo/swag"
)

// The Swagger UI pages load nothing from outside the server: the UI's
// files are embedded (swaggo/files), the page links no web fonts, and the
// online validator is off.
var index = template.Must(template.New("index").Parse(`<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="referrer" content="no-referrer">
  <title>{{.Title}}</title>
  <link rel="stylesheet" href="./swagger-ui.css">
  <link rel="icon" type="image/png" href="./favicon-32x32.png" sizes="32x32">
  <style>
    html { box-sizing: border-box; overflow-y: scroll; }
    *, *:before, *:after { box-sizing: inherit; }
    body { margin: 0; background: #fafafa; }
    .swagger-ui, .swagger-ui .info .title, .swagger-ui .opblock-tag { font-family: system-ui, -apple-system, sans-serif; }
  </style>
</head>
<body>
  <div id="swagger-ui"></div>
  <script src="./swagger-ui-bundle.js"></script>
  <script src="./swagger-ui-standalone-preset.js"></script>
  <script>
    window.onload = function () {
      window.ui = SwaggerUIBundle({
        url: {{.URL}},
        dom_id: '#swagger-ui',
        deepLinking: true,
        docExpansion: 'list',
        validatorUrl: null,
        presets: [SwaggerUIBundle.presets.apis, SwaggerUIStandalonePreset],
        plugins: [SwaggerUIBundle.plugins.DownloadUrl],
        layout: 'StandaloneLayout'
      });
    };
  </script>
</body>
</html>`))

// Init registers the Swagger UI routes:
//   - /swagger/: etherpad-go's own API (the docs package, generated by swag
//     init and embedded through the _ import), document at /swagger/doc.json;
//   - /api-docs/: etherpad-lite's REST API /api/2, document at
//     /api-docs.json (lib/api/legacy/rest.go).
func Init(app *fiber.App) {
	app.Get("/swagger/*", handler("Etherpad Go API", "doc.json", true))
	app.Get("/api-docs/*", handler("Etherpad API", "/api-docs.json", false))
}

func handler(title, docURL string, serveDoc bool) fiber.Handler {
	return func(c fiber.Ctx) error {
		p := c.Params("*")
		switch {
		case p == "" || p == "/":
			// Relative, so it works behind a proxy prefix.
			to := "index.html"
			if !strings.HasSuffix(c.Path(), "/") {
				to = path.Base(c.Path()) + "/index.html"
			}
			return c.Redirect().Status(fiber.StatusMovedPermanently).To(to)
		case p == "index.html":
			c.Type("html")
			return index.Execute(c, struct{ Title, URL string }{title, docURL})
		case serveDoc && p == "doc.json":
			doc, err := swag.ReadDoc()
			if err != nil {
				return err
			}
			return c.Type("json").SendString(doc)
		}
		name := strings.TrimPrefix(path.Clean("/"+p), "/")
		b, err := fs.ReadFile(swaggerFiles.FS, name)
		if err != nil {
			return fiber.ErrNotFound
		}
		if t := mime.TypeByExtension(path.Ext(name)); t != "" {
			c.Set(fiber.HeaderContentType, t)
		}
		return c.Send(b)
	}
}
